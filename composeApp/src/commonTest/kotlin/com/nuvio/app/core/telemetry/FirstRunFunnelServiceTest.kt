package com.nuvio.app.core.telemetry

import com.nuvio.app.core.telemetry.api.FirstRunStep
import com.nuvio.app.core.telemetry.internal.TelemetryService
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.async
import kotlinx.coroutines.awaitAll
import kotlinx.coroutines.runBlocking
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/** The funnel wired into the service: store, consent, SDK readiness, support-code order, races. */
class FirstRunFunnelServiceTest {
    private fun svc(host: FakeTelemetryHost) = TelemetryService(host, scope = CoroutineScope(Dispatchers.Unconfined))
    private fun FakeTelemetryHost.funnelEvents() = sent.filter { it.event == "first_run_step" }
    private fun ready(host: FakeTelemetryHost = FakeTelemetryHost()) = svc(host).also { it.onSdkReady() } to host

    @Test
    fun `a new install sends first_launch once and not again after a restart`() {
        val (s, host) = ready()
        s.startFirstRunFunnel { false }
        assertEquals(listOf("first_launch"), host.funnelEvents().map { it.props["step"] })
        val (s2, _) = ready(host)
        s2.startFirstRunFunnel { false }
        assertEquals(1, host.funnelEvents().size)
        host.funnelEvents().single().let {
            assertEquals(1, it.props["launch_index"]); assertEquals(0, it.props["secs_since_first_launch"])
        }
    }

    @Test
    fun `second launch has launch_index 2 on a later step`() {
        val (s, host) = ready()
        s.startFirstRunFunnel { false }
        host.now += 90_000
        val s2 = svc(host).also { it.onSdkReady() }
        s2.startFirstRunFunnel { false }
        s2.firstRunStep(FirstRunStep.FIRST_PLAYBACK, mapOf("kind" to "live", "engine" to "exo"))
        val p = host.funnelEvents().last().props
        assertEquals(2, p["launch_index"]); assertEquals(90, p["secs_since_first_launch"])
    }

    @Test
    fun `an existing support code on disk suppresses everything`() {
        val host = FakeTelemetryHost().apply { storedCode = "K7Q29MPX" }
        val (s, _) = ready(host)
        s.startFirstRunFunnel { false }
        s.firstRunStep(FirstRunStep.SOURCE_ADDED, mapOf("source_kind" to "m3u", "via" to "manual"))
        s.firstRunStep(FirstRunStep.FIRST_PLAYBACK, mapOf("kind" to "live"))
        assertTrue(host.funnelEvents().isEmpty())
    }

    @Test
    fun `each other existing-install signal suppresses everything`() {
        val (s, host) = ready()
        s.startFirstRunFunnel { true }
        s.firstRunStep(FirstRunStep.SOURCE_ADDED, emptyMap())
        assertTrue(host.funnelEvents().isEmpty())
    }

    @Test
    fun `the support code is generated by the service only after the install check read it`() {
        // Fresh host: no stored code at service construction, so the install is new even though the code now exists.
        val (s, host) = ready()
        s.startFirstRunFunnel { false }
        assertTrue(host.storedCode != null)
        assertEquals(1, host.funnelEvents().size)
    }

    @Test
    fun `consent off marks the step done and nothing is sent after consent is turned on`() {
        val host = FakeTelemetryHost(consent = false)
        val (s, _) = ready(host)
        s.startFirstRunFunnel { false }
        s.firstRunStep(FirstRunStep.SOURCE_ADDED, mapOf("source_kind" to "m3u", "via" to "manual"))
        assertTrue(host.funnelEvents().isEmpty())
        host.consent = true
        s.firstRunStep(FirstRunStep.SOURCE_ADDED, mapOf("source_kind" to "m3u", "via" to "manual"))
        val restarted = svc(host).also { it.onSdkReady() }
        restarted.startFirstRunFunnel { false }
        restarted.firstRunStep(FirstRunStep.SOURCE_ADDED, emptyMap())
        assertTrue(host.funnelEvents().isEmpty())
        // a step that first happens with consent on still goes out
        restarted.firstRunStep(FirstRunStep.FIRST_PLAYBACK, mapOf("kind" to "vod", "engine" to "exo"))
        assertEquals(listOf("first_playback"), host.funnelEvents().map { it.props["step"] })
    }

    @Test
    fun `steps before the sdk is ready are held and sent when it is`() {
        val host = FakeTelemetryHost()
        val s = svc(host)
        s.startFirstRunFunnel { false }
        s.firstRunStep(FirstRunStep.SOURCE_ADDED, mapOf("source_kind" to "addon", "via" to "manual"))
        assertTrue(host.funnelEvents().isEmpty())
        s.onSdkReady()
        assertEquals(listOf("first_launch", "source_added"), host.funnelEvents().map { it.props["step"] })
    }

    @Test
    fun `a held step is not sent if consent is off when the sdk comes up`() {
        val host = FakeTelemetryHost(consent = false)
        val s = svc(host)
        s.startFirstRunFunnel { false }
        s.onSdkReady()
        assertTrue(host.funnelEvents().isEmpty())
    }

    @Test
    fun `two concurrent calls for the same step send one event`() {
        val (s, host) = ready()
        s.startFirstRunFunnel { false }
        runBlocking {
            (1..8).map { async(Dispatchers.Default) { repeat(50) { s.firstRunStep(FirstRunStep.FIRST_PLAYBACK, mapOf("kind" to "live", "engine" to "exo")) } } }.awaitAll()
        }
        assertEquals(1, host.funnelEvents().count { it.props["step"] == "first_playback" })
    }

    @Test
    fun `the funnel event carries no diag trail and the state lives in the telemetry store`() {
        val (s, host) = ready()
        s.startFirstRunFunnel { false }
        assertTrue("diag_trail" !in host.funnelEvents().single().props)
        assertTrue(host.store.files.keys.any { it.startsWith("first_run") })
    }
}
